-- ============================================================
-- SALDO Y MOVIMIENTOS
-- ============================================================
-- Nadie puede editar esta columna directo: supabase_admin.sql solo da UPDATE sobre
-- first_name, last_name y avatar_url. El saldo cambia únicamente por estas funciones.
alter table public.profiles
    add column if not exists saldo numeric(14, 2) not null default 0;
alter table public.profiles drop constraint if exists profiles_saldo_check;
alter table public.profiles add constraint profiles_saldo_check check (saldo >= 0);

-- Historial de cada cambio de saldo (cargas del superadmin y compras).
create table if not exists public.saldo_movimientos (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    monto numeric(14, 2) not null check (monto <> 0),
    saldo_final numeric(14, 2) not null,
    motivo text not null,
    order_id bigint references public.orders(id) on delete set null,
    creado_por uuid references auth.users(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists saldo_movimientos_user_idx
    on public.saldo_movimientos(user_id, created_at desc);

alter table public.saldo_movimientos enable row level security;

drop policy if exists "saldo_movimientos_select_own" on public.saldo_movimientos;
create policy "saldo_movimientos_select_own"
    on public.saldo_movimientos for select to authenticated
    using (user_id = (select auth.uid()) or (select public.es_superadmin()));

revoke all on public.saldo_movimientos from anon, authenticated;
grant select on public.saldo_movimientos to authenticated;

