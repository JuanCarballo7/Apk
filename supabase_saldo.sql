-- Suma (monto > 0) o descuenta (monto < 0) saldo de una cuenta. Solo superadmin.
create or replace function public.admin_asignar_saldo(
    p_user_id uuid,
    p_monto numeric,
    p_motivo text default null
)
returns numeric
language plpgsql
security definer set search_path = ''
as $$
declare
    v_saldo numeric(14, 2);
begin
    if not public.es_superadmin() then
        raise exception 'NO_AUTORIZADO' using errcode = '42501';
    end if;
    if p_monto is null or p_monto = 0 or abs(p_monto) > 100000000 then
        raise exception 'MONTO_INVALIDO' using errcode = '22023';
    end if;

    select p.saldo into v_saldo
    from public.profiles p
    where p.id = p_user_id
    for update;

    if not found then
        raise exception 'USUARIO_NO_ENCONTRADO' using errcode = 'P0002';
    end if;
    if v_saldo + p_monto < 0 then
        raise exception 'SALDO_INSUFICIENTE' using errcode = 'P0001';
    end if;

    v_saldo := v_saldo + p_monto;
    update public.profiles p set saldo = v_saldo where p.id = p_user_id;

    insert into public.saldo_movimientos (user_id, monto, saldo_final, motivo, creado_por)
    values (
        p_user_id,
        p_monto,
        v_saldo,
        coalesce(nullif(trim(p_motivo), ''), case when p_monto > 0 then 'Carga de saldo' else 'Descuento de saldo' end),
        auth.uid()
    );

    return v_saldo;
end;
$$;

-- Igual que en supabase_admin.sql, pero cobra el total del saldo del comprador.
-- Si no alcanza, la excepción deshace toda la orden (stock incluido).
create or replace function public.crear_orden(p_items jsonb)
returns jsonb
language plpgsql
security definer set search_path = ''
as $$
declare
    v_user uuid := auth.uid();
    v_orden bigint;
    v_codigo text;
    v_total numeric(14, 2) := 0;
    v_saldo numeric(14, 2);
    v_item record;
    v_ticket public.tickets%rowtype;
begin
    if v_user is null then
        raise exception 'NO_AUTENTICADO' using errcode = '42501';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'CARRITO_VACIO' using errcode = '22023';
    end if;

    -- Se bloquea el perfil primero: dos compras a la vez no pueden gastar el mismo saldo.
    select p.saldo into v_saldo
    from public.profiles p
    where p.id = v_user
    for update;

    if not found then
        raise exception 'USUARIO_NO_ENCONTRADO' using errcode = 'P0002';
    end if;

    loop
        v_codigo := 'GP26-' || (100000 + floor(random() * 900000))::int::text;
        exit when not exists (select 1 from public.orders o where o.codigo = v_codigo);
    end loop;

    insert into public.orders (user_id, total, codigo, estado)
    values (v_user, 0, v_codigo, 'confirmada')
    returning id into v_orden;

    for v_item in
        select x.ticket_id, x.cantidad
        from jsonb_to_recordset(p_items) as x(ticket_id text, cantidad integer)
    loop
        if v_item.cantidad is null or v_item.cantidad < 1 or v_item.cantidad > 10 then
            raise exception 'CANTIDAD_INVALIDA' using errcode = '22023';
        end if;

        select t.* into v_ticket
        from public.tickets t
        where t.id = v_item.ticket_id and t.activo
        for update;

        if not found then
            raise exception 'NO_DISPONIBLE: %', v_item.ticket_id using errcode = 'P0001';
        end if;
        if v_ticket.stock < v_item.cantidad then
            raise exception 'SIN_STOCK: %', v_ticket.nombre using errcode = 'P0001';
        end if;

        update public.tickets t set stock = t.stock - v_item.cantidad where t.id = v_ticket.id;

        insert into public.order_items (order_id, ticket_id, nombre, cantidad, precio_unitario)
        values (v_orden, v_ticket.id, v_ticket.nombre, v_item.cantidad, v_ticket.precio);

        v_total := v_total + v_ticket.precio * v_item.cantidad;
    end loop;

    if v_saldo < v_total then
        raise exception 'SALDO_INSUFICIENTE' using errcode = 'P0001';
    end if;

    v_saldo := v_saldo - v_total;
    update public.profiles p set saldo = v_saldo where p.id = v_user;
    update public.orders o set total = v_total where o.id = v_orden;

    if v_total > 0 then
        insert into public.saldo_movimientos (user_id, monto, saldo_final, motivo, order_id, creado_por)
        values (v_user, -v_total, v_saldo, 'Compra ' || v_codigo, v_orden, v_user);
    end if;

    return jsonb_build_object('id', v_orden, 'codigo', v_codigo, 'total', v_total, 'saldo', v_saldo);
end;
$$;

-- Lista de usuarios con su email y saldo (solo superadmin).
-- Cambia las columnas que devuelve, por eso hay que borrarla antes de recrearla.
drop function if exists public.admin_listar_usuarios();
create function public.admin_listar_usuarios()
returns table (
    id uuid,
    email text,
    first_name text,
    last_name text,
    role text,
    saldo numeric,
    created_at timestamptz
)
language plpgsql
stable
security definer set search_path = ''
as $$
begin
    if not public.es_superadmin() then
        raise exception 'NO_AUTORIZADO' using errcode = '42501';
    end if;

    return query
    select p.id, u.email::text, p.first_name, p.last_name, p.role, p.saldo::numeric, p.created_at
    from public.profiles p
    join auth.users u on u.id = p.id
    order by p.created_at;
end;
$$;

revoke execute on function public.admin_asignar_saldo(uuid, numeric, text) from public, anon;
revoke execute on function public.crear_orden(jsonb) from public, anon;
revoke execute on function public.admin_listar_usuarios() from public, anon;
grant execute on function public.admin_asignar_saldo(uuid, numeric, text) to authenticated;
grant execute on function public.crear_orden(jsonb) to authenticated;
grant execute on function public.admin_listar_usuarios() to authenticated;
