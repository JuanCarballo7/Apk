-- Crea una orden confirmada con precios y stock tomados de la base (nunca del cliente).
-- supabase_saldo.sql la reemplaza por una versión que cobra del saldo: ejecutalo después de este archivo.
-- p_items: [{"ticket_id": "campo-3d", "cantidad": 2}, ...]
create or replace function public.crear_orden(p_items jsonb)
returns jsonb
language plpgsql
security definer set search_path = ''
as $$
declare
    v_user uuid := auth.uid();
    v_orden bigint;
    v_codigo text;
    v_total numeric(14, 2) := 0;
    v_item record;
    v_ticket public.tickets%rowtype;
begin
    if v_user is null then
        raise exception 'NO_AUTENTICADO' using errcode = '42501';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'CARRITO_VACIO' using errcode = '22023';
    end if;

    loop
        v_codigo := 'GP26-' || (100000 + floor(random() * 900000))::int::text;
        exit when not exists (select 1 from public.orders o where o.codigo = v_codigo);
    end loop;

    insert into public.orders (user_id, total, codigo, estado)
    values (v_user, 0, v_codigo, 'confirmada')
    returning id into v_orden;

    for v_item in
        select x.ticket_id, x.cantidad
        from jsonb_to_recordset(p_items) as x(ticket_id text, cantidad integer)
    loop
        if v_item.cantidad is null or v_item.cantidad < 1 or v_item.cantidad > 10 then
            raise exception 'CANTIDAD_INVALIDA' using errcode = '22023';
        end if;

        select t.* into v_ticket
        from public.tickets t
        where t.id = v_item.ticket_id and t.activo
        for update;

        if not found then
            raise exception 'NO_DISPONIBLE: %', v_item.ticket_id using errcode = 'P0001';
        end if;
        if v_ticket.stock < v_item.cantidad then
            raise exception 'SIN_STOCK: %', v_ticket.nombre using errcode = 'P0001';
        end if;

        update public.tickets t set stock = t.stock - v_item.cantidad where t.id = v_ticket.id;

        insert into public.order_items (order_id, ticket_id, nombre, cantidad, precio_unitario)
        values (v_orden, v_ticket.id, v_ticket.nombre, v_item.cantidad, v_ticket.precio);

        v_total := v_total + v_ticket.precio * v_item.cantidad;
    end loop;

    update public.orders o set total = v_total where o.id = v_orden;

    return jsonb_build_object('id', v_orden, 'codigo', v_codigo, 'total', v_total);
end;
$$;

-- Lista de usuarios con su email (solo superadmin).
create or replace function public.admin_listar_usuarios()
returns table (
    id uuid,
    email text,
    first_name text,
    last_name text,
    role text,
    created_at timestamptz
)
language plpgsql
stable
security definer set search_path = ''
as $$
begin
    if not public.es_superadmin() then
        raise exception 'NO_AUTORIZADO' using errcode = '42501';
    end if;

    return query
    select p.id, u.email::text, p.first_name, p.last_name, p.role, p.created_at
    from public.profiles p
    join auth.users u on u.id = p.id
    order by p.created_at;
end;
$$;

-- Cambia el rol de otro usuario (solo superadmin; nadie puede cambiarse el propio).
create or replace function public.admin_cambiar_rol(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer set search_path = ''
as $$
begin
    if not public.es_superadmin() then
        raise exception 'NO_AUTORIZADO' using errcode = '42501';
    end if;
    if p_role is null or p_role not in ('user', 'admin', 'superadmin') then
        raise exception 'ROL_INVALIDO' using errcode = '22023';
    end if;
    if p_user_id = auth.uid() then
        raise exception 'ROL_PROPIO' using errcode = '42501';
    end if;

    update public.profiles p set role = p_role where p.id = p_user_id;
    if not found then
        raise exception 'USUARIO_NO_ENCONTRADO' using errcode = 'P0002';
    end if;
end;
$$;

revoke execute on function public.crear_orden(jsonb) from public, anon;
