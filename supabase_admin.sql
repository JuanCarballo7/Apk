    id text primary key,
    zone_id text not null references public.ticket_zones(id) on update cascade,
    nombre text not null,
    categoria text not null check (categoria in ('TRIBUNA', 'GENERAL', 'HOSPITALITY')),
    dias text not null,
    precio numeric(14, 2) not null check (precio >= 0),
    stock integer not null default 0 check (stock >= 0),
    techada boolean not null default false,
    pantalla boolean not null default false,
    catering boolean not null default false,
    activo boolean not null default true,
    updated_at timestamptz not null default now()
);

